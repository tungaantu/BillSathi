/** Map an app unit (name or symbol) to a GST UQC code. Unknown units become OTH. */
export function uqcFor(unit: string | null | undefined): string {
  const key = (unit ?? '').trim().toUpperCase().replace(/\s+/g, ' ');
  if (!key) return 'OTH';
  return ALIASES[key] ?? (UQC[key] ? key : 'OTH');
}

/** Tally's "GST Reporting UOM" text, e.g. "KGS-KILOGRAMS". */
export function tallyUom(code: string): string {
  return `${code}-${UQC[code] ?? UQC.OTH}`;
}
